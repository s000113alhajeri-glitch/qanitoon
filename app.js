function bindQuranSearch(v) {
  const qq = v.querySelector("#qq"); if (!qq) return;
  qq.oninput = () => {
    const t = qq.value.trim(); const box = v.querySelector("#qres");
    if (t.length < 3) { box.innerHTML = ""; return; }
    const norm = normQ;
    const nt = norm(t);
    const bare = nt.replace(/^(ال|و|ف|ب|ل)/, "");
    const scan = (terms, limit) => { const out = []; for (const s of QURAN.surahs) { for (const a of s.a) { const na = norm(a[0]); if (terms.some(k => na.includes(k))) { out.push([s, a]); if (out.length >= limit) return out; } } } return out; };
    let out = scan([nt], 40); let mode = "";
    if (out.length < 3 && bare.length >= 3 && bare !== nt) { out = scan([bare], 40); }
    if (out.length < 3) {
      const topic = TOPICS.find(tp => tp.k === bare || tp.k === nt || tp.w.some(w => w === nt || w === bare));
      if (topic) { const terms = [...new Set([topic.k, ...topic.w].map(norm).filter(w => w.length >= 3 && !w.includes(" ")))]; out = scan(terms, 40); mode = `بحث بالموضوع: ${esc(topic.k)}`; }
    }
    box.innerHTML = (mode ? `<p class="mid">${mode}</p>` : "")
      + (out.length ? out.map(([s, a]) => `<div class="card"><div class="dua">﴿${esc(a[0])}﴾</div><div class="src"><span class="tag q">قرآن</span> ${esc(s.name)} — آية ${AR(a[1])} — <button class="chip" data-go="${a[2]}">افتح صفحة ${AR(a[2])}</button></div></div>`).join("") : `<p class="mid">لا نتائج — جرّب كلمة أقصر أو موضوعاً (السكينة، الصبر، الرزق…)</p>`);
    box.querySelectorAll("[data-go]").forEach(b => b.onclick = () => { Q.page = +b.dataset.go; go("quran"); });
  };
}

