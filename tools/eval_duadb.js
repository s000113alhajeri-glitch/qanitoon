let hit5 = 0, hit1 = 0, mrr = 0, miss = [];
GOLD.forEach(([q, exp]) => {
  const ne = DS.norm(exp);
  const hits = DS.search(q, { limit: 10 }).hits;
  const r = hits.findIndex(h => DS.norm(h.e.t).includes(ne) || (h.e.v && DS.norm(h.e.v).includes(ne)));
  const inDb = DUADB.some(e => DS.norm(e.t).includes(ne) || (e.v && DS.norm(e.v).includes(ne)));
  if (r >= 0 && r < 5) hit5++;
  if (r === 0) hit1++;
  if (r >= 0) mrr += 1 / (r + 1);
  if (!(r >= 0 && r < 5)) miss.push({ q, exp, rank: r, inDb, top: hits.slice(0, 3).map(h => h.e.t.slice(0, 50)) });
});
console.log(`recall@5 = ${(hit5 / GOLD.length * 100).toFixed(0)}%  recall@1 = ${(hit1 / GOLD.length * 100).toFixed(0)}%  MRR = ${(mrr / GOLD.length).toFixed(2)}  (n=${GOLD.length}, db=${DUADB.length})`);
miss.forEach(m => console.log(`MISS [${m.rank}] ${m.inDb ? "" : "(غير موجود في القاعدة) "}${m.q} → ${m.exp}\n     top: ${m.top.join(" | ")}`));
