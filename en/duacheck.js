function checkDua(text) {
  const t = DC_NORM(text);
  if (!t) return { level: "empty", hits: [] };
  const hits = DC_RULES.filter(r => { try { return r.test(t); } catch (e) { return false; } });
  const level = hits.some(h => h.lvl === "block") ? "block" : (hits.length ? "warn" : "ok");
  return { level, hits };
}
